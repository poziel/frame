import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

// Build-time inventory only. Optional Features adds no runtime dependency to Core.
const names = new Set<string>();
for (const root of [new URL('../src/', import.meta.url), new URL('../../features/src/', import.meta.url)]) {
  for (const file of readdirSync(root, { recursive: true }).map(String).sort()) {
    if (!/\.(css|vue|ts)$/.test(file) || file.startsWith('themes')) continue;
    for (const match of readFileSync(new URL(file.replaceAll('\\', '/'), root), 'utf8').matchAll(/--frame-[\w-]+/g)) names.add(match[0]);
  }
}
const output = '// Generated by scripts/generate-component-tokens.ts. Keep contextual defaults in component CSS.\n' +
  'export const componentTokenNames = [\n' + [...names].sort().map(name => `  ${JSON.stringify(name)},`).join('\n') + '\n] as const;\n';
const target = new URL('../src/themes/componentTokens.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Token inventory is stale. Run tokens:generate in packages/core.');
} else writeFileSync(target, output);
