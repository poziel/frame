const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = []; page.on('pageerror', error => errors.push(String(error)));
    page.setDefaultTimeout(10000);
    await page.goto(`${process.env.FRAME_TEST_URL || 'http://localhost:1420'}/@fs/${path.join(__dirname, 'fixtures/quick-input/index.html').replaceAll('\\', '/')}`);
    await page.waitForLoadState('networkidle');
    await page.getByLabel('first content', { exact: true }).waitFor();
    await page.evaluate(() => {
      fixture.first.commands.register({ id: 'test.conflict', label: 'Conflict command', source: 'Test extension', shortcut: 'Ctrl+L', when: () => true, whenLabel: 'editorFocus', run() { fixture.calls.value = 'conflict'; } });
      fixture.first.openKeybindings();
    });
    const search = page.getByRole('searchbox', { name: 'Search keyboard shortcuts' });
    await search.waitFor(); await search.fill('Test extension');
    assert.equal(await page.getByRole('columnheader', { name: 'When', exact: true }).count(), 1);
    assert.equal(await page.locator('th').first().evaluate(e => getComputedStyle(e).backgroundColor), 'rgb(32, 32, 32)');
    assert.equal(await page.getByRole('row').filter({ hasText: 'Conflict command' }).count(), 1);
    await search.fill('editorFocus'); assert.equal(await page.getByRole('row').filter({ hasText: 'Conflict command' }).count(), 1);
    await search.fill('Zebra');
    const emptyRow = page.getByRole('row').filter({ hasText: 'app.zebra' });
    assert.equal(await emptyRow.locator('.shortcut-binding').innerText(), '');
    await page.getByRole('button', { name: 'Add shortcut for Zebra', exact: true }).click();
    await page.getByRole('textbox', { name: 'Press desired key combination' }).press('Escape');
    await search.fill('Find document');
    const findRow = page.getByRole('row').filter({ hasText: 'Find document' });
    const aligned = await findRow.locator('.shortcut-action-line').evaluate(line => {
      const buttons = [...line.querySelectorAll('button')].map(button => button.getBoundingClientRect());
      const cells = [...line.closest('tr').children];
      return { count: buttons.length, centers: buttons.map(rect => rect.top + rect.height / 2), cellBorders: cells.map(cell => getComputedStyle(cell).borderBottomWidth), rowBorder: getComputedStyle(line.closest('tr')).borderBottomWidth };
    });
    assert.equal(aligned.count, 2);
    assert.equal(Math.abs(aligned.centers[0] - aligned.centers[1]) < 1, true);
    assert.equal(aligned.cellBorders.every(border => border === '0px'), true);
    assert.equal(aligned.rowBorder, '1px');
    assert.equal(await findRow.locator('.frame-keycap kbd').first().evaluate(e => getComputedStyle(e).paddingLeft), '6px');
    const edit = page.getByRole('button', { name: 'Edit shortcut for Find document', exact: true });
    await edit.click();
    const capture = page.getByRole('textbox', { name: 'Press desired key combination' });
    await capture.waitFor(); assert.equal(await capture.evaluate(e => e === document.activeElement), true);
    const dialog = page.getByRole('dialog', { name: 'Change shortcut: Find document', exact: true });
    assert.equal(await dialog.locator('footer').count(), 0);
    assert.equal(await dialog.locator('.frame-dialog-hidden-title').count(), 1);
    await dialog.getByText('Press desired key combination then press ENTER. ESC to cancels.', { exact: true }).waitFor();
    assert.equal(await page.locator('.shortcut-binding button').count(), 0);
    await capture.press('Control+l'); assert.equal(await capture.inputValue(), 'Ctrl+L');
    assert.equal(await dialog.locator('.frame-keycap kbd').count(), 2);
    assert.equal(await dialog.getByRole('group', { name: 'Ctrl+L', exact: true }).count(), 1);
    await page.getByRole('link', { name: '1 other command(s) use this keybinding. Show matches' }).waitFor();
    assert.equal(await page.evaluate(() => fixture.calls.value), '');
    await capture.press('Enter');
    assert.equal(await page.evaluate(() => fixture.first.commands.get('app.find').shortcut), 'Ctrl+L');
    assert.equal(await findRow.locator('.shortcut-action-line button').count(), 3);
    await edit.focus(); await page.keyboard.press('Enter');
    await capture.press('Control+l'); await capture.press('Tab'); await page.keyboard.press('Enter');
    assert.equal(await search.inputValue(), 'key:ctrl+l');
    assert.equal(await page.getByRole('row').filter({ hasText: 'Find document' }).count(), 1);
    assert.equal(await page.getByRole('row').filter({ hasText: 'Conflict command' }).count(), 1);
    await page.getByRole('button', { name: 'Reset shortcut for Find document', exact: true }).click();
    assert.equal(await page.evaluate(() => fixture.first.commands.get('app.find').shortcut), 'Ctrl+K');
    await search.fill('Find document'); await page.getByRole('row').filter({ hasText: 'Find document' }).dblclick(); await capture.press('Control+u'); await capture.press('Escape');
    assert.equal(await page.evaluate(() => fixture.first.commands.get('app.find').shortcut), 'Ctrl+K');
    await page.evaluate(() => fixture.first.features.setAvailable('keybindings', false));
    await search.waitFor({ state: 'hidden' });
    await page.evaluate(() => {
      fixture.first.settings.register({ id: 'application', title: 'Application', settings: [{ id: 'name', label: 'Display name', type: 'text', default: 'Initial' }] });
      fixture.first.settings.register({ id: 'advanced', title: 'Advanced', component: { setup: () => () => 'Custom settings content' } }, 'application');
      fixture.first.openSettings();
    });
    const name = page.getByRole('textbox', { name: 'Display name', exact: true });
    await name.fill('Changed'); await name.press('Tab');
    assert.equal(await page.evaluate(() => fixture.first.settings.values.name), 'Changed');
    await page.getByRole('button', { name: 'Application', exact: true }).click();
    await page.getByRole('button', { name: 'Advanced', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.settings-content')?.textContent.includes('Custom settings content'));
    assert.deepEqual(errors, []);
    console.log('Shortcut browser checks passed: search, capture, save, cancel, conflict navigation, reset, and availability.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
