"""Standalone navigation/layout primitives; fixture on port 1452."""
from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import os
with sync_playwright() as p:
    browser=p.chromium.launch()
    page=browser.new_page(viewport={"width":1000,"height":1200})
    page.set_default_timeout(6000)
    errors=[]
    page.on("pageerror",lambda error:errors.append(str(error)))
    fixture=(Path(__file__).resolve().parent/'fixtures/general-b/index.html').as_posix()
    page.goto(os.environ.get('FRAME_DOCS_URL','http://127.0.0.1:1448')+'/@fs/'+fixture)
    one=page.get_by_role('tab',name='One',exact=True)
    one.focus();one.press('ArrowRight')
    expect(page.get_by_role('tab',name='Two',exact=True)).to_be_focused()
    expect(page.locator('#tab')).to_have_text('two')
    expect(page.get_by_role('tabpanel')).to_have_text('Second content')
    page.get_by_role('button',name='Reset tab externally').click()
    expect(one).to_have_attribute('aria-selected','true')
    page.get_by_role('button',name='Review',exact=False).click()
    expect(page.locator('#step')).to_have_text('2')
    save=page.get_by_role('toolbar',name='Actions').get_by_role('button',name='Save')
    save.focus();save.press('ArrowRight')
    expect(page.get_by_role('toolbar',name='Actions').get_by_role('button',name='Close')).to_be_focused()
    page.keyboard.press('Space')
    expect(page.locator('#action')).to_have_text('close')
    source=page.get_by_role('treeitem',name='Source',exact=True)
    source.click()
    expect(page.locator('#expanded')).to_have_text('source')
    source.press('ArrowRight')
    expect(page.get_by_role('treeitem',name='index.ts',exact=True)).to_be_focused()
    page.keyboard.press('Space')
    expect(page.locator('#selected')).to_have_text('index')
    page.get_by_role('button',name='Reorder tree').click()
    expect(page.get_by_role('treeitem',name='index.ts',exact=True)).to_have_attribute('aria-selected','true')
    handle=page.get_by_role('separator',name='Resize Editor')
    before=page.locator('#layout').inner_text()
    handle.focus();handle.press('ArrowRight')
    expect(page.locator('#layout')).not_to_have_text(before)
    page.get_by_role('button',name='Guides').click()
    expect(page.get_by_role('link',name='Getting started')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('link',name='Getting started')).not_to_be_visible()
    file=page.get_by_role('menuitem',name='File',exact=True)
    file.focus();file.press('ArrowDown')
    expect(page.get_by_role('menuitem',name='New file')).to_be_focused()
    page.keyboard.press('Enter')
    expect(page.locator('#action')).to_have_text('new')
    expect(file).to_be_focused()
    assert not errors, errors
    browser.close()
    print('General navigation/layout browser checks passed')
