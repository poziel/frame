"""Focused standalone form interactions; start fixture Vite on port 1433."""
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch()
    page=browser.new_page(viewport={"width":900,"height":1200})
    errors=[]
    page.on("pageerror",lambda error:errors.append(str(error)))
    page.goto("http://localhost:1433/")
    initial=page.locator("#native-form").evaluate("el => [...new FormData(el).entries()]")
    assert initial == [["volume","3"],["choice",""],["combo","a"]], initial
    page.get_by_role("checkbox",name="Agree",exact=True).click()
    expect(page.locator("#yes")).to_have_text("true")
    page.get_by_role("switch",name="Power",exact=True).click()
    expect(page.get_by_role("switch",name="Power",exact=True)).to_be_checked()
    page.get_by_role("button",name="Bold",exact=True).press("Space")
    expect(page.get_by_role("button",name="Bold",exact=True)).to_have_attribute("aria-pressed","true")
    slider=page.get_by_role("slider",name="Volume",exact=True)
    slider.focus();slider.press("ArrowRight")
    expect(slider).to_have_attribute("aria-valuenow","4")
    select=page.get_by_role("combobox",name="Choice",exact=True)
    select.click()
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Beta",exact=True).click()
    expect(page.locator("#choice")).to_have_text("b")
    select.click()
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Empty",exact=True).click()
    expect(page.locator("#choice")).to_have_text("")
    select.click();page.keyboard.press("Escape")
    expect(select).to_be_focused()
    combo=page.get_by_role("combobox",name="Find choice",exact=True)
    combo.fill("Bet")
    expect(page.locator(".frame-reka-select-popup").get_by_role("option",name="Beta",exact=True)).to_be_visible()
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Beta",exact=True).click()
    expect(page.locator("#combo")).to_have_text("b")
    page.get_by_role("button",name="Increase",exact=True).click()
    expect(page.get_by_role("spinbutton",name="Count",exact=True)).to_have_value("5")
    page.get_by_role("textbox",name="Code 1",exact=True).fill("1234")
    expect(page.locator("#pin")).to_have_text("1234")
    tags=page.get_by_role("textbox",name="Tags",exact=True)
    tags.fill("two");tags.press("Enter")
    expect(page.locator("#tags")).to_have_text("one,two")
    page.get_by_role("button",name="Remove one",exact=True).click()
    expect(page.locator("#tags")).to_have_text("two")
    page.get_by_role("radio",name="Beta",exact=True).click()
    expect(page.get_by_role("radio",name="Beta",exact=True)).to_be_checked()
    page.get_by_role("textbox",name="Name",exact=True).fill("changed")
    expect(page.get_by_role("textbox",name="Name",exact=True)).to_have_value("changed")
    page.get_by_role("textbox",name="Details",exact=True).fill("multiline\nvalue")
    expect(page.get_by_role("textbox",name="Details",exact=True)).to_have_value("multiline\nvalue")
    expect(page.get_by_role("checkbox",name="Locked",exact=True)).to_be_disabled()
    page.get_by_label("List",exact=True).get_by_role("option",name="Beta",exact=True).click()
    expect(page.locator("#list")).to_have_text("b")
    page.get_by_label("Checks",exact=True).get_by_role("checkbox",name="Alpha",exact=True).click()
    expect(page.locator("#checks")).to_have_text("a")
    page.get_by_label("Formatting",exact=True).get_by_role("button",name="Beta",exact=True).click()
    expect(page.locator("#checks")).to_have_text("a,b")
    # Opening on selected Alpha initializes its description; keyboard highlight updates it.
    select.click()
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Alpha",exact=True).click()
    select.click()
    expect(page.locator(".frame-select-description")).to_have_text("Alpha description")
    page.keyboard.press("ArrowDown")
    expect(page.locator(".frame-select-description")).to_have_count(0)
    page.keyboard.press("Escape")
    values=page.locator("#native-form").evaluate("el => [...new FormData(el).entries()]")
    assert values == [["volume","5"],["choice","a"],["combo","b"]], values
    required_form=page.locator("#required-form")
    assert not required_form.evaluate("el => el.checkValidity()")
    expect(page.get_by_role("combobox",name="Required choice",exact=True)).to_be_focused()
    page.get_by_role("combobox",name="Required choice",exact=True).click()
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Alpha",exact=True).click()
    assert required_form.evaluate("el => el.checkValidity()")
    assert required_form.evaluate("el => [...new FormData(el).entries()]") == [["requiredChoice","a"]]
    page.get_by_role("button",name="Toggle required disabled",exact=True).click()
    assert not required_form.evaluate("el => el.checkValidity()")
    expect(page.get_by_role("combobox",name="Required search",exact=True)).to_be_focused()
    page.get_by_role("combobox",name="Required search",exact=True).fill("Bet")
    page.locator(".frame-reka-select-popup").get_by_role("option",name="Beta",exact=True).click()
    assert required_form.evaluate("el => el.checkValidity()")
    assert required_form.evaluate("el => [...new FormData(el).entries()]") == [["requiredChoice","a"],["requiredCombo","b"]]
    assert not errors,errors
    print("Standalone form browser interactions passed")
    browser.close()
