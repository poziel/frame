"""UI checks with an in-memory PTY adapter; native PTY is covered separately by Cargo tests."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={"width": 1280, "height": 800}, permissions=["clipboard-read", "clipboard-write"])
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    fixture = (Path(__file__).parent / "fixtures/terminal/index.html").resolve().as_posix()
    page.goto(f"http://localhost:1420/@fs/{fixture}")
    view = page.locator('#fixture-terminal')
    expect(view.locator('.xterm')).to_have_count(1)
    expect(view.locator('.xterm-rows')).to_contain_text('Frame terminal 1')
    page.wait_for_function('window.terminalFixture.sizes.length > 0')
    view.get_by_role('button', name='Split terminal side by side', exact=True).click()
    expect(view.locator('.xterm')).to_have_count(2)
    expect(view.locator('.frame-terminal-session')).to_have_count(2)
    expect(view.locator('.frame-terminal-session-group.split-group')).to_have_count(1)
    expect(view.locator('textarea').last).to_be_focused()
    expect(view.locator('.frame-terminal-session.active')).to_have_count(1)
    expect(view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '2')
    view.locator('textarea').first.click()
    expect(view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '1')
    view.locator('textarea').last.click()
    expect(view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '2')
    expect(view.get_by_role('button', name='Rename PowerShell', exact=True)).to_have_count(0)
    page.mouse.move(0, 0)
    row = view.locator('.frame-terminal-session').last
    expect(row.get_by_role('button', name='Close PowerShell', exact=True)).to_be_hidden()
    before = row.locator('.frame-terminal-session-select').evaluate('el => getComputedStyle(el).paddingRight')
    row.hover()
    expect(row.get_by_role('button', name='Close PowerShell', exact=True)).to_be_visible()
    after = row.locator('.frame-terminal-session-select').evaluate('el => getComputedStyle(el).paddingRight')
    assert float(after[:-2]) > float(before[:-2])
    row.get_by_role('button', name='PowerShell', exact=True).click(button='right')
    page.get_by_role('menuitem', name='Rename terminal', exact=True).click()
    view.get_by_role('textbox', name='Terminal name').fill('Build')
    view.get_by_role('textbox', name='Terminal name').press('Enter')
    expect(view.get_by_role('button', name='Build', exact=True)).to_be_visible()
    view.get_by_role('button', name='Build', exact=True).click(button='right')
    page.get_by_role('menuitem', name='Change terminal color', exact=True).click()
    view.get_by_label('Color for Build', exact=True).fill('#24aa77')
    view.get_by_role('button', name='Done', exact=True).click()
    assert page.evaluate('window.terminalFixture.terminal.sessions.value[1].color') == '#24aa77'
    # Keyboard find and no-match feedback.
    view.locator('textarea').last.focus()
    page.keyboard.press('Control+f')
    search = view.get_by_role('searchbox', name='Find in terminal')
    expect(search).to_be_focused()
    search.fill('Ready for commands')
    expect(view.get_by_text('No match', exact=True)).to_have_count(0)
    search.fill('absent text')
    expect(view.get_by_text('No match', exact=True)).to_be_visible()
    search.press('Escape')
    expect(search).to_have_count(0)
    # Native paste uses xterm's paste event and preserves bracketed-paste handling.
    view.locator('textarea').last.focus()
    page.keyboard.type('echo hello')
    page.wait_for_function("window.terminalFixture.inputs.join('').includes('echo hello')")
    page.evaluate("navigator.clipboard.writeText('pasted text')")
    page.keyboard.press('Control+Shift+v')
    page.wait_for_function("window.terminalFixture.inputs.join('').includes('pasted text')")
    # Detach the entire Vue view: no session closes, output still updates retained xterm.
    page.get_by_role('button', name='Toggle terminal', exact=True).click()
    expect(view).to_have_count(0)
    assert page.evaluate('window.terminalFixture.closed') == []
    page.evaluate("window.terminalFixture.output('2', '\\r\\noutput while hidden\\r\\nPS> ')")
    page.get_by_role('button', name='Toggle terminal', exact=True).click()
    expect(view.locator('.xterm')).to_have_count(2)
    expect(view.locator('.xterm-rows').last).to_contain_text('output while hidden')
    assert page.evaluate('window.terminalFixture.terminal.sessions.value.length') == 2
    # Dropdowns use the existing Frame menu and never open Quick input.
    view.get_by_role('button', name='Terminal options', exact=True).click()
    expect(page.get_by_role('menu', name='Terminal options', exact=True)).to_be_visible()
    expect(page.locator('.palette-backdrop')).to_have_count(0)
    page.get_by_role('menuitem', name='Separate split terminals', exact=True).click()
    expect(view.locator('.frame-terminal-session-group')).to_have_count(2)
    expect(view.locator('.frame-terminal-session-group.split-group')).to_have_count(0)
    expect(view.locator('.xterm')).to_have_count(1)
    # Switching individual groups should focus the newly displayed shell too.
    view.get_by_role('button', name='PowerShell', exact=True).click()
    expect(view.locator('textarea')).to_be_focused()
    view.get_by_role('button', name='Build', exact=True).click()
    expect(view.locator('textarea')).to_be_focused()
    # Clear only affects the active pane.
    view.get_by_role('button', name='Clear terminal', exact=True).click()
    expect(view.locator('.xterm-rows').last).not_to_contain_text('output while hidden')
    view.get_by_role('button', name='PowerShell', exact=True).click()
    expect(view.locator('.xterm-rows')).to_contain_text('Frame terminal 1')
    view.get_by_role('button', name='Build', exact=True).click()
    view.get_by_role('button', name='Close terminal session', exact=True).click()
    expect(view.locator('.xterm')).to_have_count(1)
    assert page.evaluate('window.terminalFixture.closed') == ['2']
    view.get_by_role('combobox', name='Terminal profile').click()
    page.get_by_role('option', name='Command Prompt').click()
    view.get_by_role('button', name='New terminal', exact=True).click()
    expect(view.locator('.frame-terminal-session')).to_have_count(2)
    expect(view.locator('.xterm')).to_have_count(1)
    expect(view.get_by_role('button', name='Command Prompt', exact=True)).to_be_visible()
    # Frame-managed header actions must anchor the same dropdown at the ellipsis button.
    page.get_by_role('button', name='Open header terminal', exact=True).click()
    panel = page.locator('#bottom-panel')
    header_view = panel.locator('.frame-terminal-view')
    panel.locator(':scope > header').get_by_role('button', name='New terminal', exact=True).click()
    expect(header_view.locator('textarea')).to_be_focused()
    options = panel.get_by_role('button', name='Terminal options', exact=True)
    options.click()
    menu = page.get_by_role('menu', name='Terminal options', exact=True)
    expect(menu).to_be_visible()
    expect(page.locator('.palette-backdrop')).to_have_count(0)
    bounds, anchor = menu.bounding_box(), options.bounding_box()
    assert bounds['y'] >= anchor['y'] - bounds['height'] - 12
    assert bounds['x'] + bounds['width'] >= anchor['x']
    page.keyboard.press('Escape')
    expect(menu).to_have_count(0)
    panel.get_by_role('button', name='Split terminal side by side', exact=True).click()
    expect(header_view.locator('.xterm')).to_have_count(2)
    expect(header_view.locator('textarea').last).to_be_focused()
    header_view.locator('.frame-terminal-host').first.click()
    expect(header_view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '4')
    header_view.locator('.frame-terminal-host').last.click()
    expect(header_view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '5')
    panel.get_by_role('button', name='Split terminal side by side', exact=True).click()
    expect(header_view.locator('.xterm')).to_have_count(3)
    expect(header_view.locator('textarea').last).to_be_focused()
    expect(header_view.locator('.split-group .frame-terminal-session')).to_have_count(3)
    # A session's context menu targets the clicked row without selecting a different shell.
    header_view.get_by_role('button', name='PowerShell', exact=True).first.click(button='right')
    expect(page.get_by_role('menu', name='Terminal session options')).to_be_visible()
    expect(header_view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '6')
    page.keyboard.press('Escape')
    # Keyboard users can open the same session context menu.
    first_session = header_view.get_by_role('button', name='PowerShell', exact=True).first
    first_session.focus()
    first_session.press('Shift+F10')
    expect(page.get_by_role('menu', name='Terminal session options')).to_be_visible()
    page.keyboard.press('Escape')
    panel.locator(':scope > header').get_by_role('button', name='New terminal', exact=True).click()
    expect(header_view.locator('.frame-terminal-session-group')).to_have_count(2)
    expect(header_view.locator('.split-group .frame-terminal-session')).to_have_count(3)
    header_view.get_by_role('button', name='PowerShell', exact=True).nth(2).click()
    expect(header_view.locator('textarea').last).to_be_focused()
    expect(header_view.locator('.frame-terminal-session.active')).to_have_attribute('data-session-id', '6')
    out = Path('.tmp/terminal')
    out.mkdir(parents=True, exist_ok=True)
    page.mouse.move(0, 0)
    panel.screenshot(path=str(out / 'terminal-grouped-sidebar.png'))
    options.click()
    expect(page.get_by_role('menu', name='Terminal options', exact=True)).to_be_visible()
    page.screenshot(path=str(out / 'terminal-ui.png'))
    assert not errors, errors
    browser.close()
    print('PASS: grouped splits, focus, header dropdown, session context menus, hover close, rename/color, search, paste, hidden output, clear/close; no browser errors')
