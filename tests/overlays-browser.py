"""Run with the docs dev server on port 1420; requires Playwright Chromium."""
from playwright.sync_api import sync_playwright, expect
from pathlib import Path


def contained(page, selector):
    bounds = page.locator(".workbench-body").bounding_box()
    box = page.locator(selector).last.bounding_box()
    assert bounds and box, selector
    assert box["y"] >= bounds["y"] - 1, (selector, "crosses title bar", box, bounds)
    assert box["y"] + box["height"] <= bounds["y"] + bounds["height"] + 1, (selector, "crosses status bar", box, bounds)
    assert box["x"] >= bounds["x"] - 1, (selector, "crosses left edge", box, bounds)
    assert box["x"] + box["width"] <= bounds["x"] + bounds["width"] + 1, (selector, "crosses right edge", box, bounds)


with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1180, "height": 780})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://localhost:1420/")
    page.get_by_role("button", name="Manage", exact=True).click()
    expect(page.get_by_role("menu", name="Manage", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    page.keyboard.press("Escape")
    # Title-bar menus must open entirely below the title bar too.
    page.get_by_role("menuitem", name="View", exact=True).click()
    expect(page.get_by_role("menu", name="Application menu", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    page.keyboard.press("Escape")
    page.keyboard.press("Control+Shift+P")
    expect(page.locator(".palette")).to_be_visible()
    contained(page, ".palette-backdrop")
    contained(page, ".palette")
    page.keyboard.press("Escape")
    # Exercise every overlay primitive at both edges of an actual shell.
    fixture = (Path(__file__).parent / "fixtures/overlays/index.html").resolve().as_posix()
    page.goto(f"http://localhost:1420/@fs/{fixture}")
    page.get_by_role("button", name="External menu", exact=True).click()
    expect(page.get_by_role("menu", name="External menu", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    assert page.locator(".frame-menu").evaluate("el => !!el.closest('.frame-overlay-host')")
    page.keyboard.press("ArrowRight")
    expect(page.get_by_role("menu", name="Nested choices", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    page.keyboard.press("Escape")
    for label in ["Top choice", "Bottom choice"]:
        page.get_by_role("combobox", name=label, exact=True).click()
        expect(page.locator(".frame-select-popup")).to_be_visible()
        contained(page, ".frame-select-popup")
        page.keyboard.press("End")
        page.keyboard.press("Enter")
        expect(page.get_by_role("combobox", name=label, exact=True)).to_contain_text("Choice 50")
    for label in ["Top tooltip", "Bottom tooltip"]:
        page.get_by_role("button", name=label, exact=True).hover()
        expect(page.get_by_role("tooltip")).to_be_visible()
        contained(page, ".frame-tooltip")
        page.mouse.move(2, 10)
        expect(page.get_by_role("tooltip")).to_have_count(0)
    page.get_by_role("button", name="Tall menu", exact=True).click()
    expect(page.get_by_role("menu", name="Tall menu", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    page.keyboard.press("ArrowRight")
    expect(page.get_by_role("menu", name="Nested choices", exact=True)).to_be_visible()
    for index in range(page.locator(".frame-menu").count()):
        box = page.locator(".frame-menu").nth(index).bounding_box()
        body = page.locator(".workbench-body").bounding_box()
        assert box["y"] >= body["y"] and box["y"] + box["height"] <= body["y"] + body["height"]
    page.keyboard.press("Escape")
    page.locator("#context-target").click(button="right")
    expect(page.get_by_role("menu", name="Boundary context", exact=True)).to_be_visible()
    contained(page, ".frame-menu")
    page.keyboard.press("Escape")
    page.get_by_role("button", name="Open modal", exact=True).click()
    expect(page.get_by_role("dialog", name="Boundary modal", exact=True)).to_be_visible()
    for selector in [".frame-modal", ".frame-modal-layer", ".frame-modal-backdrop"]:
        contained(page, selector)
    page.get_by_role("combobox", name="Modal choice", exact=True).click()
    contained(page, ".frame-select-popup")
    page.keyboard.press("End")
    page.keyboard.press("Enter")
    expect(page.get_by_role("combobox", name="Modal choice", exact=True)).to_contain_text("Choice 50")
    page.get_by_role("button", name="Modal tooltip", exact=True).hover()
    expect(page.get_by_role("tooltip")).to_be_visible()
    contained(page, ".frame-tooltip")
    page.mouse.move(2, 10)
    page.get_by_role("button", name="Close modal", exact=True).click()
    drag = page.get_by_role("button", name="Drag sample", exact=True).bounding_box()
    page.mouse.move(drag["x"] + drag["width"] / 2, drag["y"] + drag["height"] / 2)
    page.mouse.down()
    page.mouse.move(300, 8, steps=8)
    expect(page.locator(".view-drag-preview")).to_be_visible()
    contained(page, ".view-drag-preview")
    page.mouse.move(300, 775, steps=8)
    contained(page, ".view-drag-preview")
    page.keyboard.press("Escape")
    page.mouse.up()
    expect(page.locator(".view-drag-preview")).to_have_count(0)
    page.get_by_role("button", name="Centered quick input", exact=True).click()
    contained(page, ".palette-backdrop")
    contained(page, ".palette")
    page.keyboard.press("Escape")
    page.get_by_role("button", name="Notify", exact=True).click()
    contained(page, ".frame-notifications")
    while page.get_by_role("button", name="Dismiss notification:", exact=False).count():
        page.get_by_role("button", name="Dismiss notification:", exact=False).first.click()
    # Shells embedded away from the window origin use their own content rectangle.
    page.locator(".workbench").evaluate("el => { el.style.width = '700px'; el.style.height = '500px'; el.style.margin = '24px 30px'; }")
    page.wait_for_function("document.querySelector('.frame-overlay-host').getBoundingClientRect().top === document.querySelector('.workbench-body').getBoundingClientRect().top")
    page.get_by_role("button", name="Manage", exact=True).click()
    contained(page, ".frame-menu")
    page.keyboard.press("Escape")
    page.get_by_role("combobox", name="Bottom choice", exact=True).click()
    contained(page, ".frame-select-popup")
    page.keyboard.press("Escape")
    page.locator(".workbench").evaluate("el => { for (const key of ['width','height','margin']) el.style.removeProperty(key); }")
    # Density/status changes and very short windows must use the measured body.
    for viewport in [{"width": 720, "height": 420}, {"width": 480, "height": 250}]:
        page.set_viewport_size(viewport)
        for button in [None, "Toggle density", "Toggle status", "Toggle status"]:
            if button:
                page.get_by_role("button", name=button, exact=True).click()
            page.get_by_role("button", name="Manage", exact=True).click()
            expect(page.get_by_role("menu", name="Manage", exact=True)).to_be_visible()
            contained(page, ".frame-menu")
            page.keyboard.press("Escape")
            page.get_by_role("combobox", name="Bottom choice", exact=True).click()
            contained(page, ".frame-select-popup")
            page.keyboard.press("Escape")
    page.goto("http://localhost:1420/")
    page.get_by_role("button", name="Manage", exact=True).click()
    contained(page, ".frame-menu")
    page.screenshot(path=".tmp/overlay-boundaries.png")
    assert not errors, errors
    browser.close()
    print("Overlay boundary browser checks passed.")
