import {expect, test} from 'bun:test';
import {execFileSync, spawnSync} from 'node:child_process';
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import {tmpdir} from 'node:os';
import {basename, isAbsolute, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const command = fileURLToPath(new URL('../scripts/format.ts', import.meta.url));

/** Removes only a verified formatter fixture beneath the system temp folder. */
function removeFixture(root: string): void {
  const path = relative(resolve(tmpdir()), resolve(root));
  if (
    !path ||
    path.startsWith('..') ||
    isAbsolute(path) ||
    !basename(root).startsWith('frame-format-')
  ) {
    throw new Error('Refusing to remove an unverified fixture path');
  }
  rmSync(root, {recursive: true, force: true});
}

test('format and check share output while check mode never writes', () => {
  const root = mkdtempSync(join(tmpdir(), 'frame-format-'));
  try {
    const source = join(root, 'example.ts');
    const original = 'export class Example{first=1;second=2}';
    writeFileSync(source, original);
    const check = spawnSync(
      process.execPath,
      [command, '--check', '--root', root, source],
      {encoding: 'utf8'}
    );
    expect(check.status).toBe(1);
    expect(readFileSync(source, 'utf8')).toBe(original);
    const write = spawnSync(
      process.execPath,
      [command, '--write', '--root', root, source],
      {encoding: 'utf8'}
    );
    expect(write.status).toBe(0);
    expect(readFileSync(source, 'utf8')).toContain(
      'class Example {\n\n  first = 1;\n\n  second = 2;'
    );
    const final = spawnSync(
      process.execPath,
      [command, '--check', '--root', root, source],
      {encoding: 'utf8'}
    );
    expect(final.status).toBe(0);
  } finally {
    removeFixture(root);
  }
});

test('whole-workspace formatting preserves generated and recovery sources', () => {
  const root = mkdtempSync(join(tmpdir(), 'frame-format-ignore-'));
  try {
    mkdirSync(join(root, 'archive'));
    const archived = join(root, 'archive', 'original.ts');
    const generated = join(root, 'generated.ts');
    const editable = join(root, 'editable.css');
    writeFileSync(archived, 'const original=1');
    writeFileSync(generated, '// Generated by fixture\nconst generated=1');
    writeFileSync(editable, '.control{color:red}');
    const result = spawnSync(
      process.execPath,
      [command, '--write', '--all', '--root', root],
      {encoding: 'utf8'}
    );
    expect(result.status).toBe(0);
    expect(readFileSync(archived, 'utf8')).toBe('const original=1');
    expect(readFileSync(generated, 'utf8')).toBe(
      '// Generated by fixture\nconst generated=1'
    );
    expect(readFileSync(editable, 'utf8')).toContain('  color: red;');
  } finally {
    removeFixture(root);
  }
});

test('changed-file selection works for untracked files in a new Git repository', () => {
  const root = mkdtempSync(join(tmpdir(), 'frame-format-changed-'));
  try {
    execFileSync('git', ['init', '-q', root]);
    const source = join(root, 'new.ts');
    writeFileSync(source, 'const value=1');
    const result = spawnSync(
      process.execPath,
      [command, '--write', '--root', root],
      {encoding: 'utf8'}
    );
    expect(result.status).toBe(0);
    expect(readFileSync(source, 'utf8')).toBe('const value = 1;\n');
  } finally {
    removeFixture(root);
  }
});
