// playwright-cli -s=chat-playground run-code --filename tests/ai-chat-polish-browser.cjs
async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(String(error)));
  await page.goto('http://localhost:1420/#/playground/ai-chat'); await page.reload();
  await page.setViewportSize({ width: 1480, height: 1000 });
  const work = page.getByRole('main', { name: 'AI chat playground', exact: true });
  const chat = page.getByRole('region', { name: 'AI chat', exact: true });
  const choose = async (label, value) => { await work.getByRole('combobox', { name: label, exact: true }).click(); await page.getByRole('option', { name: value, exact: true }).click(); };
  await choose('Demo pace', 'Fast'); await choose('Demo example', 'Quick streamed answer');
  await work.getByRole('button', { name: 'Run demo example', exact: true }).click();
  await chat.locator('.frame-chat-work-summary').filter({ hasText: 'Worked for' }).waitFor({ state: 'visible' });
  check(await chat.locator('details.frame-chat-work').count() === 0, 'Thought-only replies must not offer an empty completed dropdown');
  check(await chat.locator('.frame-chat-work-events').count() === 0, 'Thought-only completed reply must have no floating border');
  await choose('Responder mode', 'Manual controls');
  const prompt = chat.getByRole('textbox', { name: 'Message', exact: true });
  await prompt.fill('Test the compact presentation'); await prompt.press('Enter');
  await work.getByRole('textbox', { name: 'Response text', exact: true }).fill('I am inspecting the output.');
  await work.getByRole('button', { name: 'Send text', exact: true }).click();
  await work.getByRole('textbox', { name: 'New group name', exact: true }).fill('Inspect project');
  await work.getByRole('button', { name: 'Create activity group', exact: true }).click();
  await work.getByRole('textbox', { name: 'Activity details', exact: true }).fill('Reading the local configuration');
  await work.getByRole('textbox', { name: 'Activity output', exact: true }).fill('<div class="example">Read palette.json</div>');
  await work.getByRole('textbox', { name: 'Output language', exact: true }).fill('html');
  await work.getByRole('button', { name: 'Start activity', exact: true }).click();
  const assistant = chat.locator('.frame-chat-message.assistant').last();
  const group = assistant.locator('.frame-chat-activity-group');
  const row = group.locator('.frame-chat-activity summary');
  await row.click();
  const output = assistant.getByRole('region', { name: 'Activity output', exact: true });
  await output.waitFor({ state: 'visible' });
  check((await output.textContent()).includes('<div class="example">'), 'HTML output must render as literal code');
  check(await output.locator('div.example').count() === 0, 'Output HTML must not execute or become DOM');
  const styles = await assistant.evaluate(element => {
    const css = target => getComputedStyle(target);
    const commentary = css(element.querySelector('.frame-chat-commentary'));
    const row = css(element.querySelector('.frame-chat-activity summary'));
    const group = css(element.querySelector('.frame-chat-activity-group-summary'));
    const output = css(element.querySelector('.frame-code-block'));
    return { foreground: css(element).color, commentary: commentary.color, commentSize: parseFloat(commentary.fontSize), rowSize: parseFloat(row.fontSize), rowColor: row.color, groupColor: group.color, radius: parseFloat(output.borderRadius), background: output.backgroundColor };
  });
  check(styles.commentary === styles.foreground, 'Commentary must use normal foreground color');
  check(styles.rowColor === styles.groupColor && styles.rowSize < styles.commentSize, 'Activity rows must be compact and muted like group headings');
  check(styles.radius > 0 && styles.background !== 'rgba(0, 0, 0, 0)', 'Output needs a rounded distinct code surface');
  const rowBox = await row.boundingBox(), groupBox = await group.locator('.frame-chat-activity-group-summary').boundingBox();
  check(Math.abs(rowBox.x - groupBox.x) <= 1, 'Activity rows must align with their group rather than indent');
  await work.getByRole('button', { name: 'Complete activity', exact: true }).click();
  check((await group.locator('.frame-chat-activity-group-summary').textContent()).includes('in '), 'Completed groups must display elapsed time');
  check(!(await group.locator('.frame-chat-activity-group-summary').textContent()).includes('Finished'), 'Finished label should be replaced by duration');
  await work.getByLabel('Add an artifact', { exact: true }).setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('A small preview document.') });
  await work.getByLabel('Add an artifact', { exact: true }).setInputFiles({ name: 'preview.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5ZkAAAAASUVORK5CYII=', 'base64') });
  check(await assistant.locator('.frame-chat-artifact').count() === 2, 'Each delivered file needs its own card');
  await assistant.getByRole('button', { name: 'Open notes.txt', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'notes.txt', exact: true });
  await dialog.waitFor({ state: 'visible' });
  await dialog.locator('.frame-viewer-text').waitFor({ state: 'visible' });
  check((await dialog.textContent()).includes('A small preview document.'), 'Open must preview the file in the viewer');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  check(await assistant.getByRole('button', { name: 'Open notes.txt', exact: true }).evaluate(element => element === document.activeElement), 'Closing preview must restore focus to Open');
  const downloaded = page.waitForEvent('download');
  await assistant.getByRole('button', { name: 'Download notes.txt', exact: true }).click();
  check((await downloaded).suggestedFilename() === 'notes.txt', 'Download must retain the filename');
  await assistant.getByRole('button', { name: 'Open preview.png', exact: true }).click();
  const imageDialog = page.getByRole('dialog', { name: 'preview.png', exact: true });
  await imageDialog.locator('.frame-viewer-image').waitFor({ state: 'visible' });
  await page.keyboard.press('Escape');
  const sash = page.getByRole('separator', { name: 'Resize secondary sidebar', exact: true });
  for (let index = 0; index < 14; index++) await sash.press('ArrowRight');
  check(await assistant.locator('.frame-chat-artifact').evaluateAll(elements => elements.every(element => element.scrollWidth <= element.clientWidth)), 'Cards must fit a narrow pane');
  await work.getByRole('button', { name: 'End turn', exact: true }).click();
  check(!(await assistant.locator('details.frame-chat-work').evaluate(element => element.open)), 'Retained work must still collapse');
  if (errors.length) throw new Error(errors.join('\n'));
  await chat.screenshot({ path: 'output/playwright/ai-chat-polished-files.png' });
  await page.goto('http://localhost:1420/@fs/D:/Dev/1-codes/frame/tests/fixtures/chat-rich/index.html');
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Standalone preview');
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('Enter');
  await page.evaluate(() => {
    const source = URL.createObjectURL(new Blob(['Standalone file preview'], { type: 'text/plain' }));
    window.richChatFixture.writer.artifact({ name: 'standalone.txt', kind: 'file', mimeType: 'text/plain', url: source });
  });
  await page.getByRole('button', { name: 'Open standalone.txt', exact: true }).click();
  const standalone = page.getByRole('dialog', { name: 'standalone.txt', exact: true });
  await standalone.locator('.frame-viewer-text').waitFor({ state: 'visible' });
  check((await standalone.textContent()).includes('Standalone file preview'), 'Artifact preview must work without a Frame instance');
  await page.keyboard.press('Escape');
  check(!errors.length, errors.join('\n'));
  return 'Empty reply disclosure, compact aligned activities, foreground commentary, code output, elapsed groups, file cards, in-app previews, downloads and narrow layout passed.';
}
