const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch(process.env.FRAME_BROWSER_CHANNEL ? { channel: process.env.FRAME_BROWSER_CHANNEL } : {});
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = []; page.on('pageerror', e => errors.push(String(e)));
    const fixture = path.join(__dirname, 'fixtures/status-bar/index.html').replaceAll('\\', '/');
    await page.goto(`${process.env.FRAME_TEST_URL || 'http://localhost:1448'}/@fs/${fixture}`);
    const bar = page.locator('.status-bar').first();
    const item = id => bar.locator(`[data-status-id="${id}"]`);
    const button = name => page.getByRole('button', { name, exact: true });
    const popup = page.getByRole('menu', { name: 'Status bar actions', exact: true });
    async function context(target, keyboard = false) {
      if (keyboard) { await target.focus(); await page.keyboard.press('Shift+F10'); }
      else await target.click({ button: 'right' });
      await popup.waitFor();
    }
    const choose = name => popup.getByRole('menuitem', { name, exact: true }).click();
    await item('branch').waitFor();
    assert.equal(await bar.locator('.status-left [data-status-id="branch"]').count(), 1);
    assert.equal(await bar.locator('.status-right [data-status-id="save"]').count(), 1);
    const center = await bar.locator('.status-message').boundingBox(), bounds = await bar.boundingBox();
    assert(Math.abs(center.x + center.width / 2 - bounds.x - bounds.width / 2) < 1);
    assert.equal(await bar.locator('.status-message button').count(), 0);
    assert.equal(await bar.locator('.status-section').first().evaluate(e => getComputedStyle(e).gap), '4px');
    await button('Save').click(); assert.equal(await page.locator('#runs').textContent(), '1');
    assert.equal(await bar.locator('.status-message').textContent(), 'Saving document');
    await button('Temporary error').click();
    await bar.locator('.status-message-error').waitFor();
    await page.waitForFunction(() => document.querySelector('.status-message')?.textContent === 'Saving document');
    await context(item('branch').locator('[data-status-control]'), true);
    assert.deepEqual(await popup.locator('[role^="menuitem"]').allTextContents(), ["Hide 'Branch'", 'Hide Badge', 'Branch', 'Save', 'Notification history', 'Manage', 'Move to Right', 'Hide Status Bar']);
    await choose('Hide Badge'); assert.equal(await item('branch').locator('.status-item-badge').count(), 0);
    await context(item('branch')); await choose('Move to Right');
    assert.equal(await bar.locator('.status-right [data-status-id="branch"]').count(), 1);
    assert(await item('branch').locator('[data-status-control]').evaluate(e => e === document.activeElement));
    await context(item('branch')); await choose("Hide 'Branch'"); await item('branch').waitFor({ state: 'detached' });
    await context(bar.locator('.status-message'));
    assert.equal(await popup.getByRole('menuitem', { name: /Move to|Hide Badge/ }).count(), 0);
    assert.equal((await popup.locator('[role^="menuitem"]').allTextContents()).at(-1), 'Hide Status Bar');
    await popup.getByRole('menuitemcheckbox', { name: 'Branch', exact: true }).click(); await item('branch').waitFor();
    await button('Notify').click();
    const history = item('notification-history');
    await history.locator('.status-item-badge').waitFor();
    await context(history); await choose('Hide Badge'); assert.equal(await history.locator('.status-item-badge').count(), 0);
    await context(history); await choose('Move to Left');
    assert.equal(await bar.locator('.status-left [data-status-id="notification-history"]').count(), 1);
    await history.getByRole('button', { name: 'Notification history', exact: true }).click();
    await page.getByRole('region', { name: 'Notifications', exact: true }).waitFor();
    await button('Hide notifications').click();
    await context(item('frame.manage')); await choose('Move to Left');
    assert.equal(await bar.locator('.status-left [data-status-id="frame.manage"]').count(), 1);
    await context(item('frame.manage')); await choose('Move to Title Bar');
    await page.locator('.titlebar').first().getByRole('button', { name: 'Manage', exact: true }).waitFor();
    assert.equal(await item('frame.manage').count(), 0);
    await context(page.locator('.titlebar').first().getByRole('button', { name: 'Manage', exact: true }));
    await choose('Move to Status Bar'); await item('frame.manage').waitFor();
    await button('Toggle shell').click(); await button('Toggle shell').click();
    await item('branch').waitFor(); assert.equal(await item('branch').locator('.status-item-badge').count(), 0);
    assert.equal(await bar.locator('.status-left [data-status-id="frame.manage"]').count(), 1);
    await button('Long branch').click();
    await page.setViewportSize({ width: 520, height: 900 });
    assert(await bar.evaluate(e => e.scrollWidth <= e.clientWidth));
    const narrowCenter = await bar.locator('.status-message').boundingBox(), narrowBar = await bar.boundingBox();
    assert(Math.abs(narrowCenter.x + narrowCenter.width / 2 - narrowBar.x - narrowBar.width / 2) < 1);
    await context(bar.locator('.status-message')); await choose('Hide Status Bar'); await bar.waitFor({ state: 'hidden' });
    assert(await page.locator('#other-shell .status-bar').isVisible());
    await button('Show status bar').click(); await bar.waitFor();
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.goto(process.env.FRAME_TEST_URL || 'http://localhost:1448');
    const docsBar = page.locator('.status-bar');
    await docsBar.getByRole('button', { name: 'Manage', exact: true }).waitFor();
    await docsBar.getByRole('button', { name: 'Notification history', exact: true }).waitFor();
    assert.equal(await docsBar.locator('.status-left [data-status-id="docs.name"]').count(), 1);
    assert.deepEqual(await docsBar.locator('.status-right [data-status-id]').evaluateAll(items => items.map(item => item.dataset.statusId)), ['docs.version', 'notification-history', 'frame.manage']);
    if (process.env.FRAME_SCREENSHOT_PATH) await page.screenshot({ path: process.env.FRAME_SCREENSHOT_PATH });
    assert.deepEqual(errors, []);
    console.log('Status bar geometry, text/actions, transient errors, context menus, badges, moves, history, Manage, remount retention, narrow layout and instance isolation passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
