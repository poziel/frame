from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect

fixture = (Path(__file__).resolve().parent / 'fixtures/general-c/index.html').as_posix()
url = os.environ.get('FRAME_DOCS_URL', 'http://127.0.0.1:1448')
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(f'{url}/@fs/{fixture}')
    page.get_by_role('button', name='Edit profile', exact=True).click()
    expect(page.get_by_role('dialog', name='Edit profile')).to_be_visible()
    page.get_by_label('Name', exact=True).fill('Ada')
    page.get_by_role('button', name='Nested actions', exact=True).click()
    page.get_by_role('menuitem', name='Edit', exact=True).click()
    expect(page.get_by_test_id('selection')).to_have_text('edit')
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_be_hidden()
    expect(page.get_by_role('button', name='Edit profile', exact=True)).to_be_focused()
    page.get_by_role('button', name='Delete profile?', exact=True).click()
    expect(page.get_by_role('alertdialog')).to_be_visible()
    page.get_by_role('button', name='Cancel', exact=True).click()
    expect(page.get_by_test_id('confirmed')).to_have_text('false')
    page.get_by_role('button', name='Delete profile?', exact=True).click()
    page.get_by_role('button', name='Delete', exact=True).click()
    expect(page.get_by_test_id('confirmed')).to_have_text('true')
    page.get_by_role('button', name='Drawer settings', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_be_hidden()
    page.get_by_role('button', name='Open details', exact=True).click()
    page.get_by_label('Details value').fill('Details')
    page.keyboard.press('Escape')
    page.get_by_role('button', name='File actions', exact=True).click()
    expect(page.get_by_role('menuitem', name='Unavailable', exact=True)).to_have_attribute('data-disabled', '')
    page.keyboard.press('ArrowDown')
    page.keyboard.press('Enter')
    expect(page.get_by_test_id('selection')).to_have_text('edit')
    page.get_by_role('button', name='Context actions', exact=True).click(button='right')
    page.get_by_role('menuitem', name='Delete', exact=True).click()
    expect(page.get_by_test_id('selection')).to_have_text('delete')
    page.get_by_role('button', name='Hover details', exact=True).hover()
    expect(page.get_by_text('Profile information')).to_be_visible()
    page.get_by_role('button', name='Notify', exact=True).click()
    expect(page.get_by_text('Your changes were saved.')).to_be_visible()
    page.get_by_role('button', name='Dismiss notification').click()
    expect(page.get_by_text('Your changes were saved.')).to_be_hidden()
    assert not errors, errors
    browser.close()
    print('PASS: standalone General overlays, keyboard focus restoration, nested menu, alert confirmation, drawer, popover, hover card and toast')
