"""Run with docs dev server: uv run --with playwright python tests/ai-chat-browser.py."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={"width": 1440, "height": 1050}, permissions=["clipboard-read", "clipboard-write"])
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://localhost:1420")
    page.get_by_role("button", name="AI chat", exact=True).click()
    for label in ["Hide secondary sidebar", "Hide panel"]:
        button = page.get_by_role("button", name=label)
        if button.is_visible(): button.click()
    room = page.locator(".frame-ai-chat")
    prompt = room.get_by_role("textbox", name="Message", exact=True)
    send = room.get_by_role("button", name="Send message", exact=True)
    expect(send).to_be_disabled()
    prompt.fill("   ")
    expect(send).to_be_disabled()
    prompt.fill("First prompt")
    expect(send).to_be_enabled()
    assert room.locator(".frame-chat-composer").evaluate("el => getComputedStyle(el).borderTopColor") == "rgb(0, 120, 212)"
    prompt.press("Shift+Enter")
    prompt.type("Second line")
    expect(prompt).to_have_value("First prompt\nSecond line")
    prompt.press("Enter")
    expect(room.get_by_role("button", name="Stop response")).to_be_visible()
    expect(room.locator(".frame-chat-work-summary")).to_contain_text("Working for")
    assert room.locator(".frame-chat-composer").evaluate("el => getComputedStyle(el, '::before').animationName") == "frame-chat-orbit"
    page.emulate_media(reduced_motion="reduce")
    assert room.locator(".frame-chat-composer").evaluate("el => getComputedStyle(el, '::before').animationName") == "none"
    page.emulate_media(reduced_motion="no-preference")
    expect(room.locator(".frame-chat-current-thought")).to_contain_text("simulated thinking")
    expect(send).to_be_visible(timeout=10000)
    assistant = room.locator(".frame-chat-message.assistant")
    expect(assistant.locator(".frame-chat-text")).to_have_count(1)
    expect(assistant.locator(".frame-chat-text")).to_contain_text("\n\nThis is a second message")
    expect(assistant.locator(".frame-chat-work-summary")).to_contain_text("Worked for")
    expect(assistant.locator(".frame-chat-work")).not_to_have_attribute("open", "")
    prompt.focus()
    page.mouse.move(0, 0)
    expect(assistant.locator(".frame-chat-message-actions")).to_have_css("opacity", "0")
    assistant.hover()
    expect(assistant.locator(".frame-chat-message-actions")).to_have_css("opacity", "1")
    assistant.get_by_role("button", name="Copy message", exact=True).click()
    assert "This is a second message" in page.evaluate("navigator.clipboard.readText()")
    user = room.locator(".frame-chat-message.user")
    user.hover()
    expect(user.locator(".frame-chat-message-meta")).to_have_css("opacity", "1")
    prompt.fill("Unsent draft")
    user.hover()
    user.get_by_role("button", name="Rewind to this message").click()
    expect(prompt).to_have_value("First prompt\nSecond line")
    expect(room.locator(".editing")).to_have_count(1)
    expect(room.locator(".after-rewind")).to_have_count(1)
    original = room.get_by_role("button", name="Jump to original prompt")
    expect(original).to_have_text("First prompt\nSecond line")
    prompt.fill("Completely different draft")
    expect(original).to_have_text("First prompt\nSecond line")
    expect(original).to_have_css("text-overflow", "ellipsis")
    room.locator(".frame-chat-transcript").evaluate("el => { el.style.flex = 'none'; el.style.height = '100px'; el.scrollTop = el.scrollHeight; }")
    original.click()
    assert room.locator(".frame-chat-transcript").evaluate("el => el.scrollTop") < 30
    room.locator(".frame-chat-transcript").evaluate("el => el.removeAttribute('style')")
    room.locator(".frame-chat-rewind-notice").get_by_role("button", name="Cancel rewind").click()
    expect(prompt).to_have_value("Unsent draft")
    expect(room.locator(".after-rewind")).to_have_count(0)
    user.hover()
    user.get_by_role("button", name="Rewind to this message").click()
    user.hover()
    user.get_by_role("button", name="Cancel rewind").click()
    expect(prompt).to_have_value("Unsent draft")
    user.hover()
    user.get_by_role("button", name="Rewind to this message").click()
    prompt.fill("Replaced prompt")
    prompt.press("Enter")
    expect(send).to_be_visible(timeout=10000)
    expect(room.locator(".frame-chat-message")).to_have_count(2)
    expect(user.locator(".frame-chat-text")).to_have_text("Replaced prompt")
    room.get_by_role("button", name="Add attachment").click()
    menu = page.get_by_role("menu", name="Add context")
    expect(menu.get_by_role("menuitem", name="Files…")).to_be_visible()
    expect(menu.get_by_role("menuitem", name="Folder…")).to_be_visible()
    menu.get_by_role("menuitem", name="Current workspace").press("Enter")
    expect(room.get_by_role("button", name="Remove Current workspace")).to_be_visible()
    room.get_by_role("button", name="Remove Current workspace").click()
    room.locator('input[type="file"]').first.set_input_files({"name": "example.txt", "mimeType": "text/plain", "buffer": b"hello"})
    expect(room.get_by_role("button", name="Remove example.txt")).to_be_visible()
    room.get_by_role("button", name="Remove example.txt").click()
    page.get_by_role("checkbox", name="Reverse message alignment").check()
    expect(room.locator(".user.left")).to_have_count(1)
    expect(room.locator(".assistant.right")).to_have_count(1)
    page.get_by_role("checkbox", name="Reverse message alignment").uncheck()
    prompt.fill("Another turn")
    prompt.press("Enter")
    expect(room.get_by_role("button", name="Stop response")).to_be_visible()
    room.get_by_role("button", name="Stop response").click()
    expect(room.locator(".assistant").last.locator(".frame-chat-work-summary")).to_contain_text("Stopped")
    assistant.first.hover()
    room.get_by_role("button", name="Forge conversation from here").first.click()
    expect(room.locator(".frame-chat-message")).to_have_count(2)
    expect(prompt).to_have_value("")
    # Preserve the complete room and a narrow room as reviewable artifacts.
    Path(".tmp").mkdir(exist_ok=True)
    room.screenshot(path=".tmp/ai-chat-wide.png")
    page.add_style_tag(content=".frame-chat-demo { max-width: 340px; }")
    assert room.evaluate("el => el.scrollWidth <= el.clientWidth")
    room.screenshot(path=".tmp/ai-chat-narrow.png")
    # Overlay scrollbars must remain below action tooltips in either alignment.
    page.add_style_tag(content=".frame-chat-transcript { flex: none; height: 180px; } .frame-chat-message.assistant .frame-chat-text { min-height: 400px; }")
    transcript = room.locator(".frame-chat-transcript")
    for reversed_chat in [False, True]:
        page.get_by_role("checkbox", name="Reverse message alignment").set_checked(reversed_chat)
        transcript.evaluate("el => el.scrollTop = 0")
        if reversed_chat:
            assistant.first.hover()
            button = assistant.first.get_by_role("button", name="Forge conversation from here")
            button.scroll_into_view_if_needed()
        else:
            user.hover()
            button = user.get_by_role("button", name="Rewind to this message")
        button.hover()
        tooltip = page.get_by_role("tooltip")
        expect(tooltip).to_be_visible()
        bar = page.locator(".frame-overlay-scrollbar").first
        expect(bar).to_be_attached()
        assert int(tooltip.evaluate("el => getComputedStyle(el).zIndex")) > int(bar.evaluate("el => getComputedStyle(el).zIndex"))
        assert tooltip.evaluate("el => el.parentElement.classList.contains('frame-overlay-host')")
        page.mouse.move(0, 0)
    # The jump control follows text growth, context chips, and shrinkage.
    for draft in ["Short", "Line\n" * 12, "Short again"]:
        prompt.fill(draft)
        transcript.evaluate("el => el.scrollTop = 0")
        jump = room.get_by_role("button", name="Jump to latest", exact=True)
        expect(jump).to_be_visible()
        composer_box = room.locator(".frame-chat-composer").bounding_box()
        jump_box = jump.bounding_box()
        assert composer_box and jump_box
        gap = composer_box["y"] - jump_box["y"] - jump_box["height"]
        assert 6 <= gap <= 10, gap
    jump.click()
    expect(room.get_by_role("button", name="Jump to latest", exact=True)).to_have_count(0)
    assert not errors, errors
    browser.close()
    print("AI chat browser checks passed: streaming, ordered parts, copy, rewind, attachments, alignment, stop, forge, reduced motion and narrow layout.")
