"""Terminal layout checks using the Docs dev server and an in-memory PTY adapter."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1280, "height": 850})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    fixture = (Path(__file__).parent / 'fixtures/terminal/index.html').resolve().as_posix()
    page.goto(f'http://localhost:1420/@fs/{fixture}')
    view = page.locator('#fixture-terminal')
    expect(view.locator('.xterm')).to_have_count(1)
    expect(view.locator('.frame-terminal-sidebar')).to_have_count(0)
    view.get_by_role('button', name='Split terminal side by side', exact=True).click()
    view.get_by_role('button', name='Split terminal side by side', exact=True).click()
    expect(view.locator('.xterm')).to_have_count(3)
    expect(view.locator('.frame-terminal-sidebar')).to_be_visible()
    panes = view.locator('.frame-terminal-pane')
    def widths(): return [round(panes.nth(i).bounding_box()['width']) for i in range(3)]
    before = widths()
    sash = view.get_by_role('separator', name='Resize terminal pane 1', exact=True)
    box = sash.bounding_box()
    page.mouse.move(box['x'] + box['width'] / 2, box['y'] + 40)
    page.mouse.down()
    page.mouse.move(box['x'] + box['width'] / 2 + 60, box['y'] + 40, steps=6)
    page.mouse.up()
    after = widths()
    assert after[0] > before[0] + 50, (before, after)
    assert after[1] < before[1] - 50, (before, after)
    assert abs(after[2] - before[2]) < 3, (before, after)
    sidebar = view.locator('.frame-terminal-sidebar')
    old_width = sidebar.bounding_box()['width']
    sidebar_sash = view.get_by_role('separator', name='Resize terminal sidebar', exact=True)
    sidebar_sash.focus()
    sidebar_sash.press('ArrowLeft')
    assert sidebar.bounding_box()['width'] > old_width + 5
    box = sidebar_sash.bounding_box()
    page.mouse.move(box['x'] + box['width'] / 2, box['y'] + 50)
    page.mouse.down()
    page.mouse.move(box['x'] + box['width'] / 2 - 50, box['y'] + 50, steps=5)
    page.mouse.up()
    resized_sidebar = sidebar.bounding_box()['width']
    assert resized_sidebar > old_width + 50
    scaled = widths()
    assert abs(scaled[0] / scaled[1] - after[0] / after[1]) < .03
    page.locator('#terminal-container').evaluate("el => el.style.width = '330px'")
    page.wait_for_function("document.querySelector('#fixture-terminal .frame-terminal-sidebar').getBoundingClientRect().width < 200")
    page.locator('#terminal-container').evaluate("el => el.style.width = ''")
    page.wait_for_function('width => Math.abs(document.querySelector("#fixture-terminal .frame-terminal-sidebar").getBoundingClientRect().width - width) < 2', arg=resized_sidebar)
    restored = widths()
    assert abs(restored[0] / restored[1] - after[0] / after[1]) < .03
    # Orientation changes preserve all sessions and the visibility preference.
    view.get_by_role('button', name='Terminal options', exact=True).click()
    page.get_by_role('menuitemcheckbox', name='Show terminals as tabs', exact=True).click()
    expect(sidebar).to_have_count(0)
    tabs = view.get_by_role('tablist', name='Terminal tabs')
    expect(tabs).to_be_visible()
    expect(tabs.get_by_role('tab')).to_have_count(3)
    tabs.get_by_role('tab').first.click()
    expect(tabs.get_by_role('tab').first).to_have_attribute('aria-selected', 'true')
    expect(view.locator('textarea').first).to_be_focused()
    tabs.get_by_role('tab').first.focus()
    tabs.get_by_role('tab').first.press('ArrowRight')
    expect(tabs.get_by_role('tab').nth(1)).to_be_focused()
    expect(tabs.get_by_role('tab').nth(1)).to_have_attribute('aria-selected', 'true')
    assert tabs.bounding_box()['y'] < panes.first.bounding_box()['y']
    view.get_by_role('button', name='Terminal options', exact=True).click()
    page.get_by_role('menuitemcheckbox', name='Show terminal tabs', exact=True).click()
    expect(tabs).to_have_count(0)
    view.get_by_role('button', name='Terminal options', exact=True).click()
    page.get_by_role('menuitemcheckbox', name='Show terminal tabs', exact=True).click()
    expect(tabs).to_be_visible()
    # Parent height changes must resize the emulator, without any outer overflow.
    old_rows = page.evaluate("window.terminalFixture.sizes.filter(s => s.id === '3').at(-1).rows")
    page.locator('#terminal-container').evaluate("el => el.style.height = '260px'")
    page.wait_for_function("Math.abs(document.querySelector('#terminal-container').clientHeight - document.querySelector('#fixture-terminal').getBoundingClientRect().height) < 2")
    assert view.evaluate('el => el.scrollHeight <= el.clientHeight + 1')
    page.wait_for_function("rows => window.terminalFixture.sizes.filter(s => s.id === '3').at(-1).rows < rows", arg=old_rows)
    page.locator('#terminal-container').evaluate("el => el.style.height = '460px'")
    page.wait_for_function("Math.abs(document.querySelector('#fixture-terminal').getBoundingClientRect().height - 460) < 2")
    page.wait_for_function("rows => window.terminalFixture.sizes.filter(s => s.id === '3').at(-1).rows > rows", arg=old_rows)
    assert panes.first.bounding_box()['y'] + panes.first.bounding_box()['height'] <= view.bounding_box()['y'] + view.bounding_box()['height'] + 1
    out = Path('.tmp/terminal')
    out.mkdir(parents=True, exist_ok=True)
    view.screenshot(path=str(out / 'terminal-tabs.png'))
    # Enabled tabs still disappear automatically when a single session remains.
    view.get_by_role('button', name='Close terminal session', exact=True).click()
    view.get_by_role('button', name='Close terminal session', exact=True).click()
    expect(view.locator('.xterm')).to_have_count(1)
    expect(tabs).to_have_count(0)
    view.get_by_role('button', name='Terminal options', exact=True).click()
    expect(page.get_by_role('menuitemcheckbox', name='Show terminal tabs', exact=True)).to_have_attribute('aria-checked', 'true')
    page.keyboard.press('Escape')
    view.get_by_role('button', name='New terminal', exact=True).click()
    expect(tabs).to_be_visible()
    view.get_by_role('button', name='Terminal options', exact=True).click()
    page.get_by_role('menuitemcheckbox', name='Show terminals as sidebar', exact=True).click()
    expect(sidebar).to_be_visible()
    assert abs(sidebar.bounding_box()['width'] - resized_sidebar) < 2
    # The Frame-managed view must fit the actual panel content as the outer sash moves.
    page.get_by_role('button', name='Open header terminal', exact=True).click()
    panel = page.locator('#bottom-panel')
    panel.locator(':scope > header').get_by_role('button', name='New terminal', exact=True).click()
    managed = panel.locator('.frame-terminal-view')
    expect(managed.locator('.xterm')).to_have_count(1)
    def fits_panel():
        content = panel.locator(':scope > .panel-content').bounding_box()
        terminal_box = managed.bounding_box()
        assert abs(content['height'] - terminal_box['height']) < 2, (content, terminal_box)
    fits_panel()
    outer = page.get_by_role('separator', name='Resize bottom panel', exact=True)
    outer.focus()
    outer.press('ArrowUp')
    fits_panel()
    assert panel.locator(':scope > .panel-content').evaluate('el => el.scrollHeight <= el.clientHeight + 1')
    assert not errors, errors
    browser.close()
    print('PASS: pane drag, sidebar resize, top tabs, visibility preference, one-session hiding, parent height fitting')
