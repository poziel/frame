async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(String(error)));
  const open = async id => { await page.goto(`http://localhost:1420/#/features/${id}`); await page.getByRole('tab', { name: 'Interactive demo', exact: true }).click(); return page.getByRole('region', { name: `${id} interactive demo`, exact: true }); };
  const menu = async (row, name) => { await row.click({ button: 'right' }); await page.getByRole('menuitem', { name, exact: true }).click(); };
  await page.setViewportSize({ width: 1500, height: 1050 });
  const promptDemo = await open('ai-prompt');
  const prompt = promptDemo.getByRole('textbox', { name: 'Message', exact: true });
  await prompt.fill('Compose independently');
  await prompt.dispatchEvent('keydown', { key: 'Enter', isComposing: true });
  check(await prompt.inputValue() === 'Compose independently', 'IME confirmation submitted the prompt');
  await prompt.press('Enter');
  check((await promptDemo.getByRole('status').innerText()).includes('Submitted: Compose independently'), 'Standalone prompt did not emit submission');
  await promptDemo.getByRole('checkbox', { name: 'Working state', exact: true }).click();
  await promptDemo.getByRole('button', { name: 'Stop response', exact: true }).click();
  check((await promptDemo.getByRole('status').innerText()).includes('Stop requested'), 'Standalone stop is missing');
  await promptDemo.getByRole('checkbox', { name: 'Disable prompt', exact: true }).click();
  check(await prompt.isDisabled(), 'Disabled prompt remained editable');

  const historyDemo = await open('ai-history');
  const history = historyDemo.getByRole('region', { name: 'AI history', exact: true });
  const newPrompt = history.getByRole('textbox', { name: 'New conversation message', exact: true });
  check(await history.getByRole('button', { name: 'New conversation', exact: true }).count() === 0, 'History has a redundant new-conversation button');
  await newPrompt.fill('First project'); await newPrompt.press('Enter');
  await history.getByRole('button', { name: 'First project', exact: true }).waitFor();
  await newPrompt.fill('Second project'); await newPrompt.press('Enter');
  check(await history.getByRole('button', { name: /^Delete / }).count() === 0, 'History exposes inline delete buttons');
  await menu(history.getByRole('button', { name: 'First project', exact: true }), 'Rename');
  const dialog = page.getByRole('dialog', { name: 'Rename conversation', exact: true });
  check(await dialog.getByRole('button', { name: 'Save name', exact: true }).evaluate(el=>el.parentElement === Array.from(el.closest('[role=dialog]').querySelectorAll('button')).find(button=>button.textContent==='Cancel')?.parentElement), 'Save and Cancel must share the dialog footer');
  await dialog.getByRole('textbox', { name: 'Conversation name', exact: true }).fill('Renamed project');
  await dialog.getByRole('button', { name: 'Save name', exact: true }).click();
  await history.getByRole('button', { name: 'Renamed project', exact: true }).waitFor();
  check(await history.getByRole('button', { name: 'Renamed project', exact: true }).evaluate(el=>el===document.activeElement), 'Rename did not restore focus to its row');
  await menu(history.getByRole('button', { name: 'Renamed project', exact: true }), 'Pin');
  check((await history.getByRole('listitem').first().innerText()).includes('Renamed project'), 'Pinned row did not move first');
  await menu(history.getByRole('button', { name: 'Renamed project', exact: true }), 'Archive');
  check(await history.getByRole('button', { name: 'Renamed project', exact: true }).count() === 0, 'Archived conversation remains in the active list');
  check(await history.getByRole('button', { name: 'View archived conversations', exact: true }).evaluate(el=>el.closest('.frame-ai-history-footer')?.previousElementSibling?.tagName === 'NAV'), 'Archive link must sit below the conversation list');
  await history.getByRole('button', { name: 'View archived conversations', exact: true }).click();
  const archived = history.getByRole('button', { name: 'Renamed project', exact: true });
  await archived.focus(); await archived.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Restore', exact: true }).click();
  await history.getByRole('button', { name: 'Back to conversations', exact: true }).click();
  await menu(history.getByRole('button', { name: 'Renamed project', exact: true }), 'Delete');
  check(await history.getByRole('listitem').count() === 1, 'Delete did not remove only the selected conversation');

  const chatDemo = await open('ai-chat');
  const bundle = page.locator('.secondary-region .frame-ai-chat-bundle');
  await bundle.waitFor();
  const initialWidth = await bundle.evaluate(el=>el.clientWidth);
  if (initialWidth >= 720) {
    const handle = await page.getByRole('separator', { name: 'Resize secondary sidebar', exact: true }).boundingBox();
    await page.mouse.move(handle.x+handle.width/2, handle.y+100); await page.mouse.down(); await page.mouse.move(handle.x+initialWidth-460, handle.y+100, {steps:8}); await page.mouse.up();
  }
  check(await page.locator('.workbench').count() === 1, 'Combined chat added a nested Frame');
  const fresh = bundle.getByRole('textbox', { name: 'New conversation message', exact: true });
  await bundle.locator('input[type=file]').first().setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Local attachment') });
  await fresh.fill('Combined project'); await fresh.press('Enter');
  const conversation = bundle.getByRole('region', { name: 'AI conversation', exact: true });
  await conversation.waitFor();
  const back = bundle.getByRole('button', { name: 'Back to conversation history', exact: true });
  check(await back.evaluate(el=>getComputedStyle(el).position === 'absolute' && el.getBoundingClientRect().width <= 32), 'History navigation must be a small floating icon');
  const backBounds = await back.boundingBox(), firstMessage = await conversation.locator('.frame-chat-message').first().boundingBox();
  check(firstMessage.y >= backBounds.y + backBounds.height, 'Floating back control overlaps the first message');
  check(await conversation.getByRole('textbox', { name: 'Message', exact: true }).evaluate(el=>el===document.activeElement), 'Creating from history did not focus the conversation composer');
  check((await conversation.getByRole('log', { name: 'Conversation' }).innerText()).includes('notes.txt'), 'History composer lost attachments when creating a conversation');
  await conversation.getByRole('button', { name: 'Stop response', exact: true }).click();
  await bundle.getByRole('button', { name: 'Back to conversation history', exact: true }).click();
  await fresh.waitFor({ state: 'visible' });
  check(await fresh.evaluate(el=>el===document.activeElement), 'Back to history did not focus the new-conversation composer');
  await bundle.getByRole('button', { name: 'Combined project', exact: true }).click();
  await conversation.waitFor({ state: 'visible' });
  const divider = page.getByRole('separator', { name: 'Resize secondary sidebar', exact: true });
  const bounds = await divider.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 100); await page.mouse.down(); await page.mouse.move(bounds.x - 430, bounds.y + 100, { steps: 8 }); await page.mouse.up();
  check(await bundle.evaluate(el => el.clientWidth) >= 720, 'Could not widen sidebar to test responsive chat');
  check(await bundle.getByRole('navigation', { name: 'Conversation history' }).isVisible(), 'Wide chat must show history beside the conversation');
  check(await conversation.isVisible(), 'Wide chat hid the conversation');
  await chatDemo.getByRole('button', { name: 'Remove AI view', exact: true }).click();
  check(await page.getByRole('separator', { name: 'Resize secondary sidebar', exact: true }).count() === 0, 'Empty sidebar stayed open');
  await chatDemo.getByRole('button', { name: 'Create AI view', exact: true }).click();
  check((await page.locator('.secondary-region').innerText()).includes('Combined project'), 'Recreating the view lost caller-owned conversation state');
  check(errors.length === 0, errors.join('\n'));
  return 'Independent prompt, history context actions and keyboard access, shared attachments, responsive combined chat, and view lifecycle passed.';
}
