"""Run against the Vite dev server: uv run --with playwright python tests/loading-browser.py."""
from playwright.sync_api import sync_playwright, expect
import os
BASE_URL=os.environ.get("FRAME_TEST_URL", "http://localhost:1420").rstrip("/")
from pathlib import Path

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1000, "height": 700})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    fixture = (Path(__file__).parent / "fixtures/loading/index.html").resolve().as_posix()
    page.goto(f"{BASE_URL}/@fs/{fixture}")
    region = page.locator("#region")
    expect(region).to_have_attribute("aria-busy", "false")
    expect(page.locator("#counts")).to_have_text("1/0/0")
    expect(page.locator("#inside")).to_be_visible()
    page.locator("#start").click()
    expect(region).to_have_attribute("aria-busy", "true")
    expect(region.get_by_role("status")).to_have_accessible_name("Calculating")
    expect(page.locator("#inside")).to_be_hidden()
    assert page.locator("#inside").evaluate("el => !!el.closest('[inert]')")
    page.locator("#region").click(position={"x": 20, "y": 20})
    expect(page.locator("#inside-count")).to_have_text("0")
    # Neither Tab navigation nor programmatic focus can enter the region.
    page.locator("#outside").focus()
    page.keyboard.press("Tab")
    assert page.evaluate("document.activeElement.id") != "inside"
    page.locator("#inside").evaluate("el => el.focus()")
    assert page.evaluate("document.activeElement.id") != "inside"
    page.locator("#outside").click()
    expect(page.locator("#counts")).to_have_text("1/0/1")
    expect(region).to_have_attribute("aria-busy", "false")
    expect(page.locator("#counts")).to_have_text("1/0/2")
    expect(page.locator("#inside")).to_be_visible()
    expect(region.get_by_role("status")).to_have_count(0)
    expect(page.locator("#initial-region")).to_have_attribute("aria-busy", "false")
    expect(page.locator("#initial-result")).to_have_text("Child initialized")
    page.locator("#inside").focus()
    assert page.evaluate("document.activeElement.id") == "inside"
    loaders = page.locator("#gallery .frame-loader")
    expect(loaders).to_have_count(44)
    page.wait_for_function("Array.from(document.querySelectorAll('#gallery .frame-loader')).every(el => el.querySelector('[aria-hidden]')?.shadowRoot?.childElementCount > 0)")
    assert loaders.evaluate_all("els => els.every(el => el.querySelector('[aria-hidden]')?.shadowRoot?.childElementCount > 0)")
    page.locator("#change-loader").click()
    expect(page.locator("#dynamic-loader frame-ldrs-tailspin")).to_have_attribute("size", "48")
    expect(page.locator("#dynamic-loader frame-ldrs-tailspin")).to_have_attribute("color", "red")
    page.locator("#change-loader").click()
    expect(page.locator("#dynamic-loader frame-ldrs-ring")).to_have_attribute("size", "24")
    for position in ["above", "below", "left", "right"]:
        loading = page.locator(f"#position-{position}")
        expect(loading.get_by_role("status")).to_have_accessible_name("Please wait")
        label = loading.locator(".frame-loading-label").bounding_box()
        animation = loading.locator(".frame-loader").bounding_box()
        assert label and animation
        if position == "above": assert label["y"] + label["height"] <= animation["y"]
        if position == "below": assert animation["y"] + animation["height"] <= label["y"]
        if position == "left": assert label["x"] + label["width"] <= animation["x"]
        if position == "right": assert animation["x"] + animation["width"] <= label["x"]
    expect(page.locator("#text-only .frame-loader")).to_have_count(0)
    expect(page.locator("#text-only .frame-loading-label")).to_have_text("Text without animation")
    expect(page.locator("#loader-only .frame-loading-label")).to_have_count(0)
    expect(page.locator("#loader-only").get_by_role("status")).to_have_accessible_name("Loading…")
    expect(page.locator("#custom-indicator")).to_be_visible()
    expect(page.locator("#custom-loader .frame-loading-label")).to_have_text("Custom animation")
    expect(page.locator("#custom-layout")).to_be_visible()
    expect(page.locator("#custom-overlay .frame-loader")).to_have_count(0)
    page.emulate_media(reduced_motion="reduce")
    expect(page.locator("#gallery .frame-loader").first.locator("[aria-hidden]")).to_have_attribute("speed", "0")
    page.screenshot(path=".tmp/loading-components.png")
    assert not errors, errors
    page.goto(BASE_URL+"/")
    page.get_by_role("button", name="Loader", exact=True).click()
    expect(page.get_by_role("heading", name="Loader", exact=True)).to_be_visible()
    expect(page.locator(".loader-gallery .frame-loader")).to_have_count(44)
    page.get_by_role("button", name="Use helix", exact=True).click()
    expect(page.get_by_role("button", name="Use helix", exact=True)).to_have_attribute("aria-pressed", "true")
    expect(page.locator(".loader-selection code")).to_contain_text('variant="helix"')
    page.get_by_role("searchbox", name="Filter loader styles").fill("newtons")
    expect(page.locator(".loader-gallery .frame-loader")).to_have_count(1)
    expect(page.get_by_role("button", name="Use newtons-cradle", exact=True)).to_be_visible()
    page.get_by_role("searchbox", name="Filter loader styles").fill("")
    expect(page.locator(".loader-gallery .frame-loader")).to_have_count(44)
    page.get_by_role("heading", name="Loader", exact=True).scroll_into_view_if_needed()
    page.screenshot(path=".tmp/loader-gallery.png")
    page.get_by_role("button", name="Loading region", exact=True).click()
    expect(page.get_by_role("heading", name="Loading region", exact=True)).to_be_visible()
    page.get_by_role("button", name="Outside action · 0", exact=True).click()
    expect(page.get_by_role("button", name="Outside action · 1", exact=True)).to_be_visible()
    region = page.locator(".loading-example-region")
    expect(region).to_have_attribute("aria-busy", "false")
    page.get_by_role("textbox", name="Workspace name", exact=True).fill("Keep this name")
    page.get_by_role("button", name="Reload from inside", exact=True).click()
    expect(region).to_have_attribute("aria-busy", "true")
    expect(region).to_have_attribute("aria-busy", "false")
    expect(page.get_by_role("textbox", name="Workspace name", exact=True)).to_have_value("Keep this name")
    page.get_by_role("checkbox", name="Keep preview visible", exact=True).check()
    page.get_by_role("textbox", name="Loading text", exact=True).fill("Building preview")
    expect(region.get_by_role("status")).to_have_accessible_name("Building preview")
    page.get_by_role("combobox", name="Text position", exact=True).click()
    page.get_by_role("option", name="Above loader", exact=True).click()
    expect(region.locator(".frame-loading-indicator")).to_have_class("frame-loading-indicator text-above")
    page.get_by_role("checkbox", name="Show loader", exact=True).uncheck()
    expect(region.locator(".frame-loader")).to_have_count(0)
    expect(region.locator(".frame-loading-label")).to_have_text("Building preview")
    page.get_by_role("checkbox", name="Show loader", exact=True).check()
    page.get_by_role("checkbox", name="Show text", exact=True).uncheck()
    expect(region.locator(".frame-loading-label")).to_have_count(0)
    expect(region.get_by_role("status")).to_have_accessible_name("Building preview")
    page.get_by_role("checkbox", name="Show text", exact=True).check()
    region.scroll_into_view_if_needed()
    page.screenshot(path=".tmp/loading-docs.png")
    assert not errors, errors
    browser.close()
    print("Loading browser checks passed: 44 variants, four text positions, optional text/animation, custom slots, region isolation, mounted content, async completion, keyboard access, reduced motion, docs previews.")
