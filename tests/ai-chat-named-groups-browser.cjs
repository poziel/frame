// playwright-cli -s=chat-playground run-code --filename tests/ai-chat-named-groups-browser.cjs
async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(String(error)));
  await page.goto('http://localhost:1420/#/playground/ai-chat'); await page.reload();
  await page.setViewportSize({ width: 1500, height: 1000 });
  const work = page.getByRole('main', { name: 'AI chat playground', exact: true });
  const chat = page.getByRole('region', { name: 'AI chat', exact: true });
  const choose = async (label, option) => {
    await work.getByRole('combobox', { name: label, exact: true }).click();
    await page.getByRole('option', { name: option, exact: true }).click();
  };
  const combos = work.getByRole('combobox');
  check(await combos.count() === 7, 'All playground selectors should be FrameSelect controls');
  check(await combos.evaluateAll(elements => elements.every(element => element.classList.contains('frame-select'))), 'Selectors must use Frame styling');
  check(await work.getByRole('combobox', { name: 'Group for new activities', exact: true }).isDisabled(), 'Group selection must be disabled before a prompt');
  await chat.getByRole('textbox', { name: 'Message', exact: true }).fill('Test named groups');
  await chat.getByRole('textbox', { name: 'Message', exact: true }).press('Enter');
  await work.getByRole('textbox', { name: 'New group name' }).fill('Inspect project');
  await work.getByRole('button', { name: 'Create activity group', exact: true }).click();
  check((await chat.locator('.frame-chat-activity-group-summary').first().textContent()).includes('Inspect project'), 'New empty named group should be visible');
  await work.getByRole('textbox', { name: 'Activity label', exact: true }).fill('Read files');
  await work.getByRole('button', { name: 'Start activity', exact: true }).click();
  await work.getByRole('textbox', { name: 'New group name' }).fill('Run checks');
  await work.getByRole('button', { name: 'Create activity group', exact: true }).click();
  await work.getByRole('textbox', { name: 'Activity label', exact: true }).fill('Run tests');
  await work.getByRole('button', { name: 'Start activity', exact: true }).click();
  await choose('Group for new activities', 'Inspect project');
  await work.getByRole('textbox', { name: 'Activity label', exact: true }).fill('Read another file');
  await work.getByRole('button', { name: 'Start activity', exact: true }).click();
  let groups = chat.locator('.frame-chat-activity-group');
  check(await groups.count() === 2, 'Choosing an earlier group must reuse it');
  check(await groups.first().locator('.frame-chat-activity').count() === 2, 'Both selected actions must be in Inspect project');
  await choose('Active activity', 'Read files');
  await work.getByRole('textbox', { name: 'Activity output', exact: true }).fill('Updated selected activity output');
  await work.getByRole('button', { name: 'Update activity', exact: true }).click();
  await groups.first().locator('.frame-chat-activity summary').first().click();
  check((await groups.first().getByRole('region', { name: 'Activity output', exact: true }).textContent()).includes('Updated selected'), 'Activity FrameSelect must target the selected operation');
  await choose('Text type', 'Final answer');
  await work.getByRole('textbox', { name: 'Response text' }).fill('Final result');
  await work.getByRole('button', { name: 'Send text', exact: true }).click();
  await work.getByRole('textbox', { name: 'Response text' }).fill(' + appended');
  await choose('Answer to append to', 'Final result');
  await work.getByRole('button', { name: 'Append text', exact: true }).click();
  check((await chat.locator('.frame-chat-answer').textContent()).trim() === 'Final result + appended', 'Answer FrameSelect must target the selected message');
  await choose('Group for new activities', 'Automatic grouping');
  await work.getByRole('textbox', { name: 'Activity label', exact: true }).fill('Automatic action');
  await work.getByRole('button', { name: 'Start activity', exact: true }).click();
  check(await groups.count() === 3, 'Automatic grouping remains available alongside named groups');
  await work.getByRole('button', { name: 'End turn', exact: true }).click();
  check(!(await chat.locator('.frame-chat-work').evaluate(element => element.open)), 'Work must still collapse on completion');
  await work.getByRole('button', { name: 'Reset session', exact: true }).click();
  await chat.getByRole('textbox', { name: 'Message', exact: true }).fill('Fresh turn');
  await chat.getByRole('textbox', { name: 'Message', exact: true }).press('Enter');
  check((await work.getByRole('combobox', { name: 'Group for new activities', exact: true }).textContent()).includes('Automatic grouping'), 'Reset must discard stale selected groups');
  const typeSelect = work.getByRole('combobox', { name: 'Text type', exact: true });
  await typeSelect.focus(); await typeSelect.press('ArrowDown');
  await page.keyboard.press('End'); await page.keyboard.press('Enter');
  check((await typeSelect.textContent()).includes('Final answer'), 'FrameSelect must support keyboard selection');
  if (errors.length) throw new Error(errors.join('\n'));
  return 'Named group creation/selection, automatic fallback, all FrameSelect controls, answer append, activity update, reset and completion passed.';
}
