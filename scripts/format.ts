import {execFileSync} from 'node:child_process';
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {getFileInfo} from 'prettier';
import {SourceFormatter} from './sourceFormatter';

/**
 * Runs the same complete project style pipeline in write and check modes.
 * Defaults to changed Git files; explicit paths and --all support migrations.
 */
class FormattingCommand {

  /** Location of the shared formatter, configuration, and standards. */
  private readonly frameRoot = resolve(
    dirname(fileURLToPath(import.meta.url)),
    '..'
  );

  /** Canonical formatter used for every supported source language. */
  private readonly formatter = new SourceFormatter(
    join(this.frameRoot, '.prettierrc.json')
  );

  /** Non-source directories never traversed by a workspace migration. */
  private readonly excluded = new Set([
    '.git',
    'node_modules',
    'dist',
    'dist-ssr',
    'target',
    'output',
    'coverage',
    '.tmp',
    '.ai-workspace',
    '.playwright-cli',
    '.agents',
    '.codex',
    '.aws',
    '.vite',
    'archive',
    'extracted-workspace',
    'docs-tauri-original',
    'licenses',
    'autogenerated',
    'gen',
  ]);

  /**
   * Formats or checks changed files, explicit paths, or entire workspaces.
   *
   * @param args - Mode, optional roots, and optional source paths.
   * @returns Zero for success, one for style differences or failures.
   */
  async run(args: readonly string[]): Promise<number> {
    if (args.includes('--help')) {
      console.log(
        'bun scripts/format.ts --write|--check [--all] [--root DIR] [--with-native] [paths...]'
      );
      console.log(
        'Default: changed Git files. Without Git metadata: maintained files in the selected root.'
      );
      return 0;
    }
    const write = args.includes('--write');
    let root = this.frameRoot;
    const paths: string[] = [];
    for (let index = 0; index < args.length; index++) {
      const arg = args[index]!;
      if (arg === '--root') {
        const directory = args[++index];
        if (!directory) throw new Error('--root requires a directory');
        root = resolve(directory);
      } else if (!arg.startsWith('--')) {
        paths.push(resolve(arg));
      } else if (
        !['--write', '--check', '--all', '--with-native'].includes(arg)
      ) {
        throw new Error(`Unknown formatting option: ${arg}`);
      }
    }
    if (write && args.includes('--check'))
      throw new Error('Choose either --write or --check');
    const roots = [root];
    const native = resolve(this.frameRoot, '../frame-native');
    if (args.includes('--with-native') && native !== root && existsSync(native))
      roots.push(native);
    const candidates = new Set<string>();
    if (paths.length) {
      for (const path of paths)
        this.files(path).forEach((file) => candidates.add(file));
    } else {
      for (const workspace of roots) {
        const files = args.includes('--all')
          ? this.files(workspace)
          : (this.changedFiles(workspace) ?? this.files(workspace));
        files.forEach((file) => candidates.add(file));
      }
    }
    let checked = 0;
    let changed = 0;
    let failed = false;
    for (const filename of [...candidates].sort()) {
      if (!existsSync(filename) || !this.supported(filename)) continue;
      try {
        const info = await getFileInfo(filename, {
          ignorePath: join(this.frameRoot, '.prettierignore'),
          resolveConfig: false,
        });
        if (info.ignored || !info.inferredParser) continue;
        const source = readFileSync(filename, 'utf8');
        if (
          /^\s*(?:\/\/|\/\*|<!--)[^\n]*(?:@generated|generated by|do not edit)/i.test(
            source.slice(0, 500)
          )
        )
          continue;
        checked++;
        const result = await this.formatter.format(source, filename);
        if (result === source) continue;
        changed++;
        if (write) {
          if (readFileSync(filename, 'utf8') !== source)
            throw new Error(
              'Source changed concurrently; formatting was skipped'
            );
          writeFileSync(filename, result);
        }
        console.log(`${write ? 'Formatted' : 'Needs formatting'}: ${filename}`);
      } catch (error) {
        failed = true;
        console.error(
          `${filename}: ${error instanceof Error ? error.message : String(error)}`
        );
      }
    }
    console.log(
      `${checked} editable files checked; ${changed} ${write ? 'formatted' : 'need formatting'}.`
    );
    return failed || (!write && changed > 0) ? 1 : 0;
  }

  /**
   * Collects staged, unstaged, and untracked changes without using shell globs.
   *
   * @param root - Workspace whose Git metadata is inspected.
   * @returns Changed paths, or undefined when the workspace has no Git root.
   */
  private changedFiles(root: string): string[] | undefined {
    try {
      const git = (args: string[]) =>
        execFileSync('git', ['-C', root, ...args], {
          encoding: 'utf8',
          stdio: ['ignore', 'pipe', 'ignore'],
        });
      if (resolve(git(['rev-parse', '--show-toplevel']).trim()) !== root)
        return;
      return (
        git(['diff', '--name-only', '-z', '--']) +
        git(['diff', '--cached', '--name-only', '-z', '--']) +
        git(['ls-files', '--others', '--exclude-standard', '-z'])
      )
        .split('\0')
        .filter(Boolean)
        .map((path) => resolve(root, path));
    } catch {
      return undefined;
    }
  }

  /**
   * Discovers explicit source paths without traversing dependency symlinks.
   *
   * @param root - Editable file or directory supplied by the caller.
   * @returns Candidate paths before parser and generated-file filtering.
   */
  private files(root: string): string[] {
    if (statSync(root).isFile()) return this.supported(root) ? [root] : [];
    const result: string[] = [];
    for (const entry of readdirSync(root, {withFileTypes: true})) {
      const path = join(root, entry.name);
      if (entry.isDirectory() && !this.excluded.has(entry.name))
        result.push(...this.files(path));
      else if (entry.isFile() && this.supported(path)) result.push(path);
    }
    return result;
  }

  /**
   * Restricts formatting to maintained text languages and excludes lockfiles.
   *
   * @param filename - Candidate absolute source path.
   * @returns Whether the file can participate in project formatting.
   */
  private supported(filename: string): boolean {
    const parts = relative(this.frameRoot, filename).split(/[\\/]/);
    return (
      !parts.some((part) => this.excluded.has(part)) &&
      !/[/\\]tauri[/\\]permissions[/\\]schemas[/\\]/.test(filename) &&
      !filename.endsWith('package-lock.json') &&
      /\.(?:[cm]?[jt]sx?|vue|html?|css|scss|jsonc?|md|mdx|ya?ml)$/.test(
        filename
      )
    );
  }
}

process.exitCode = await new FormattingCommand().run(process.argv.slice(2));
